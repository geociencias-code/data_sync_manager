import os
import json
import logging
import subprocess
import tempfile
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional, Callable

from app.config import RCLONE_CONF_PATH

logger = logging.getLogger("sync_app.rclone")

class RcloneManager:
    """
    Manages rclone configuration, connectivity testing,
    file discovery (lsjson), and transfers.
    """

    @classmethod
    def get_rclone_binary(cls) -> str:
        """
        Locates the rclone binary cross-platform:
        1. Checks project bin/ directory (rclone or rclone.exe).
        2. Checks system PATH via shutil.which('rclone').
        """
        import shutil
        from app.config import BIN_DIR
        
        exe_name = "rclone.exe" if os.name == "nt" else "rclone"
        local_bin = BIN_DIR / exe_name
        if local_bin.exists():
            return str(local_bin)
            
        found = shutil.which("rclone") or shutil.which("rclone.exe")
        if found:
            return found
            
        return exe_name

    @classmethod
    def obscure_password(cls, password: str) -> str:
        """Obfuscates a password using rclone obscure."""
        if not password:
            return ""
        try:
            res = subprocess.run(
                [cls.get_rclone_binary(), "obscure", password],
                capture_output=True,
                text=True,
                check=True
            )
            return res.stdout.strip()
        except Exception as e:
            logger.error(f"Error obscuring password: {e}")
            return password

    @classmethod
    def generate_config_file(cls, settings: Dict[str, str], target_path: Optional[Path] = None) -> Path:
        """
        Generates rclone.conf dynamically from settings.
        Target path defaults to RCLONE_CONF_PATH.
        """
        conf_path = target_path or RCLONE_CONF_PATH
        
        # 1. Source SFTP Section
        sftp_pass = settings.get("source_pass", "")
        obscured_sftp_pass = cls.obscure_password(sftp_pass) if sftp_pass else ""
        
        lines = [
            "# Auto-generated by SFTP to S3/FTP Data Sync App",
            "[sftp_source]",
            "type = sftp",
            f"host = {settings.get('source_host', '').strip()}",
            f"user = {settings.get('source_user', '').strip()}",
            f"port = {settings.get('source_port', '22').strip() or '22'}",
            "known_hosts_file = none",
        ]
        
        if obscured_sftp_pass:
            lines.append(f"pass = {obscured_sftp_pass}")
            
        key_file = settings.get("source_key_file", "").strip()
        if key_file and not os.path.isdir(key_file):
            # Forward slashes for rclone configuration across Windows, Linux and macOS
            clean_key = key_file.replace("\\", "/")
            lines.append(f"key_file = {clean_key}")
            
        lines.append("") # Blank line
        
        # 2. Destination Section (S3 or FTP)
        dest_type = settings.get("dest_type", "s3").lower()
        if dest_type == "s3":
            raw_provider = settings.get("s3_provider", "AWS").strip()
            access_key = settings.get("s3_access_key", "").strip()
            secret_key = settings.get("s3_secret_key", "").strip()
            region = settings.get("s3_region", "us-east-1").strip() or "us-east-1"
            endpoint = settings.get("s3_endpoint", "").strip().rstrip("/")
            
            # S3 endpoints like RustFS, MinIO, Ceph, etc. should use provider 'Other' or 'Minio'
            # If a custom endpoint is specified and provider is left as default 'AWS', use 'Other'
            provider = raw_provider
            if endpoint and provider.upper() in ("AWS", ""):
                provider = "Other"

            lines.extend([
                "[dest_remote]",
                "type = s3",
                f"provider = {provider}",
                f"access_key_id = {access_key}",
                f"secret_access_key = {secret_key}",
                f"region = {region}",
                "chunk_size = 5M",
                "upload_concurrency = 2",
                "force_path_style = true",
                "no_check_bucket = true",
            ])
            if endpoint:
                lines.append(f"endpoint = {endpoint}")
        else:
            # FTP Destination
            ftp_host = settings.get("ftp_host", "").strip()
            ftp_user = settings.get("ftp_user", "").strip()
            ftp_port = settings.get("ftp_port", "21").strip() or "21"
            ftp_pass = settings.get("ftp_pass", "")
            
            lines.extend([
                "[dest_remote]",
                "type = ftp",
                f"host = {ftp_host}",
                f"user = {ftp_user}",
                f"port = {ftp_port}",
                "concurrency = 0",
                "idle_timeout = 1m",
            ])
            if ftp_port == "990":
                lines.append("tls = true")
            elif ftp_port == "21":
                lines.append("tls = false")

            if ftp_pass:
                lines.append(f"pass = {cls.obscure_password(ftp_pass)}")
                
        lines.append("")
        
        conf_content = "\n".join(lines)
        conf_path.parent.mkdir(parents=True, exist_ok=True)
        conf_path.write_text(conf_content, encoding="utf-8")
        
        # Protect config file permissions
        try:
            os.chmod(conf_path, 0o600)
        except Exception:
            pass
            
        return conf_path

    @classmethod
    def test_source_connection(cls, settings: Dict[str, str]) -> Tuple[bool, str]:
        """Tests connectivity to the SFTP source."""
        if not settings.get("source_host") or not settings.get("source_user"):
            return False, "Faltan datos obligatorios del host o usuario SFTP."

        key_file = settings.get("source_key_file", "").strip()
        if key_file and os.path.isdir(key_file):
            return False, (
                f"'{key_file}' es una carpeta/directorio, no un archivo de clave SSH (ej. id_rsa, key.pem). "
                f"Si los archivos a transferir están en esa carpeta, debes colocarla en el campo 'Directorio Remoto SFTP a Escanear' "
                f"y dejar 'Ruta Clave Privada SSH' vacía si te autenticas con contraseña."
            )

        with tempfile.NamedTemporaryFile("w+", suffix=".conf", delete=False) as tmp:
            tmp_path = Path(tmp.name)
            
        try:
            cls.generate_config_file(settings, target_path=tmp_path)
            src_path = settings.get("source_path", "").strip()
            target = f"sftp_source:{src_path}" if src_path else "sftp_source:"
            
            cmd = [
                cls.get_rclone_binary(), "lsf",
                "--config", str(tmp_path),
                "--contimeout", "10s",
                "--timeout", "15s",
                "--max-depth", "1",
                target
            ]
            
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=20)
            if proc.returncode == 0:
                return True, "Conexión SFTP exitosa y directorio accesible."
            else:
                err = proc.stderr.strip() or proc.stdout.strip() or f"Código de error {proc.returncode}"
                return False, f"Error al conectar con SFTP: {err}"
        except subprocess.TimeoutExpired:
            return False, "Tiempo de espera agotado (Timeout) al conectar con SFTP."
        except Exception as e:
            return False, f"Excepción al probar SFTP: {str(e)}"
        finally:
            if tmp_path.exists():
                tmp_path.unlink()

    @classmethod
    def test_dest_connection(cls, settings: Dict[str, str]) -> Tuple[bool, str]:
        """Tests connectivity to the Destination (S3 or FTP)."""
        dest_type = settings.get("dest_type", "s3").lower()
        if dest_type == "s3":
            if not settings.get("s3_access_key") or not settings.get("s3_secret_key"):
                return False, "Faltan credenciales Access Key o Secret Key de S3."
        else:
            if not settings.get("ftp_host") or not settings.get("ftp_user"):
                return False, "Faltan host o usuario de FTP."

        with tempfile.NamedTemporaryFile("w+", suffix=".conf", delete=False) as tmp:
            tmp_path = Path(tmp.name)
            
        try:
            cls.generate_config_file(settings, target_path=tmp_path)
            
            if dest_type == "s3":
                bucket = settings.get("s3_bucket", "").strip().strip("/")
                s3_path = settings.get("s3_path", "").strip().strip("/")
                if bucket:
                    target = f"dest_remote:{bucket}" if not s3_path else f"dest_remote:{bucket}/{s3_path}"
                else:
                    target = "dest_remote:"
            else:
                raw_path = settings.get("ftp_path", "").strip()
                is_abs = raw_path.startswith("/")
                ftp_path = raw_path.strip("/")
                if ftp_path:
                    target = f"dest_remote:/{ftp_path}" if is_abs else f"dest_remote:{ftp_path}"
                else:
                    target = "dest_remote:"

            cmd = [
                cls.get_rclone_binary(), "lsd",
                "--config", str(tmp_path),
                "--contimeout", "10s",
                "--timeout", "15s",
                "--no-check-certificate",
                "--s3-no-check-bucket",
                "--max-depth", "1",
                target
            ]
            
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=20)
            if proc.returncode == 0:
                return True, f"Conexión exitosa a destino {dest_type.upper()}."
            else:
                err = proc.stderr.strip() or proc.stdout.strip() or f"Código de error {proc.returncode}"
                # If target was a specific FTP subfolder that doesn't exist yet, test root
                if dest_type == "ftp" and target != "dest_remote:":
                    fallback_cmd = [
                        cls.get_rclone_binary(), "lsd",
                        "--config", str(tmp_path),
                        "--contimeout", "10s",
                        "--timeout", "15s",
                        "--no-check-certificate",
                        "--max-depth", "1",
                        "dest_remote:"
                    ]
                    f_proc = subprocess.run(fallback_cmd, capture_output=True, text=True, timeout=20)
                    if f_proc.returncode == 0:
                        return True, f"Conexión exitosa al servidor FTP (Nota: la carpeta '{raw_path}' se creará automáticamente en la primera transferencia)."
                return False, f"Error al conectar con {dest_type.upper()}: {err}"
        except subprocess.TimeoutExpired:
            return False, f"Tiempo de espera agotado al conectar a {dest_type.upper()}."
        except Exception as e:
            return False, f"Excepción al probar destino: {str(e)}"
        finally:
            if tmp_path.exists():
                tmp_path.unlink()

    @classmethod
    def list_source_files(
        cls, 
        settings: Dict[str, str], 
        recursive: bool = True,
        config_path: Optional[Path] = None,
        min_age: Optional[str] = None,
        process_callback: Optional[Callable[[subprocess.Popen], None]] = None
    ) -> Tuple[bool, List[Dict[str, Any]], str]:
        """
        Runs `rclone lsjson` against the SFTP source to map all available files.
        If min_age is provided (e.g. '2m'), only returns files older than that duration.
        Returns (success, files_data, error_message).
        """
        conf_to_use = config_path or RCLONE_CONF_PATH
        proc = None
        try:
            cls.generate_config_file(settings, target_path=conf_to_use)
            raw_src = settings.get("source_path", "").strip()
            is_abs = raw_src.startswith("/")
            src_path = raw_src.strip("/")
            if src_path:
                target = f"sftp_source:/{src_path}" if is_abs else f"sftp_source:{src_path}"
            else:
                target = "sftp_source:"
            
            cmd = [
                cls.get_rclone_binary(), "lsjson",
                "--config", str(conf_to_use),
                "--files-only",
                "--contimeout", "15s",
                "--timeout", "60s"
            ]
            if min_age:
                cmd.extend(["--min-age", str(min_age)])
            if recursive:
                cmd.append("-R")
            cmd.append(target)
            
            proc = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True
            )
            if process_callback:
                process_callback(proc)

            stdout, stderr = proc.communicate(timeout=90)
            if proc.returncode == 0:
                data = json.loads(stdout)
                return True, data, ""
            else:
                err = (stderr or "").strip() or (stdout or "").strip() or f"Código {proc.returncode}"
                return False, [], f"Error al listar archivos SFTP: {err}"
        except subprocess.TimeoutExpired:
            if proc:
                try:
                    proc.kill()
                except Exception:
                    pass
            return False, [], "Tiempo de espera agotado al escanear SFTP."
        except json.JSONDecodeError as e:
            return False, [], f"Error decodificando respuesta de rclone: {str(e)}"
        except Exception as e:
            return False, [], f"Excepción al listar archivos: {str(e)}"
        finally:
            if proc:
                try:
                    if proc.stdout:
                        proc.stdout.close()
                    if proc.stderr:
                        proc.stderr.close()
                except Exception:
                    pass

    @classmethod
    def scan_source_files(
        cls, 
        settings: Dict[str, Any], 
        recursive: bool = True,
        max_depth: Optional[int] = 2
    ) -> Tuple[bool, List[Dict[str, Any]], str]:
        """
        Scans and previews files on the SFTP source using a temporary isolated configuration.
        Used for on-demand preview in the UI before or during task configuration.
        """
        with tempfile.NamedTemporaryFile("w+", suffix=".conf", delete=False) as tmp:
            tmp_path = Path(tmp.name)
            
        try:
            cls.generate_config_file(settings, target_path=tmp_path)
            raw_src = settings.get("source_path", "").strip()
            is_abs = raw_src.startswith("/")
            src_path = raw_src.strip("/")
            if src_path:
                target = f"sftp_source:/{src_path}" if is_abs else f"sftp_source:{src_path}"
            else:
                target = "sftp_source:"
                
            cmd = [
                cls.get_rclone_binary(), "lsjson",
                "--config", str(tmp_path),
                "--files-only",
                "--contimeout", "10s",
                "--timeout", "25s"
            ]
            if recursive:
                cmd.append("-R")
            if max_depth:
                cmd.extend(["--max-depth", str(max_depth)])
            cmd.append(target)
            
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
            if proc.returncode == 0:
                data = json.loads(proc.stdout)
                return True, data, ""
            else:
                err = proc.stderr.strip() or proc.stdout.strip() or f"Código de error {proc.returncode}"
                return False, [], f"Error al escanear SFTP: {err}"
        except subprocess.TimeoutExpired:
            return False, [], "Tiempo de espera agotado al escanear archivos en SFTP."
        except json.JSONDecodeError as e:
            return False, [], f"Respuesta no válida de rclone: {str(e)}"
        except Exception as e:
            return False, [], f"Excepción al escanear: {str(e)}"
        finally:
            if tmp_path.exists():
                tmp_path.unlink()

    @classmethod
    def get_destination_target(cls, settings: Dict[str, str], rel_path: str) -> str:
        """Computes the full rclone destination target string for a given relative path."""
        dest_type = settings.get("dest_type", "s3").lower()
        clean_rel = rel_path.lstrip("/")
        
        if dest_type == "s3":
            bucket = settings.get("s3_bucket", "").strip().strip("/")
            s3_path = settings.get("s3_path", "").strip().strip("/")
            
            parts = [bucket] if bucket else []
            if s3_path:
                parts.append(s3_path)
            parts.append(clean_rel)
            
            full_dst = "/".join(parts)
            return f"dest_remote:{full_dst}"
        else:
            raw_path = settings.get("ftp_path", "").strip()
            is_abs = raw_path.startswith("/")
            ftp_path = raw_path.strip("/")
            parts = [ftp_path] if ftp_path else []
            parts.append(clean_rel)
            full_dst = "/".join(parts)
            return f"dest_remote:/{full_dst}" if is_abs else f"dest_remote:{full_dst}"

    @classmethod
    def get_source_target(cls, settings: Dict[str, str], rel_path: str) -> str:
        """Computes the full rclone source target string for a given relative path."""
        raw_src = settings.get("source_path", "").strip()
        is_abs = raw_src.startswith("/")
        src_path = raw_src.strip("/")
        clean_rel = rel_path.lstrip("/")
        
        if src_path:
            full_path = f"/{src_path}/{clean_rel}" if is_abs else f"{src_path}/{clean_rel}"
            return f"sftp_source:{full_path}"
        return f"sftp_source:{clean_rel}"

    @classmethod
    def execute_file_transfer(
        cls, 
        settings: Dict[str, str], 
        file_path: str,
        config_path: Optional[Path] = None,
        process_callback: Optional[Any] = None,
        progress_callback: Optional[Any] = None
    ) -> Tuple[bool, str]:
        """
        Transfers a single file from SFTP to Destination using rclone copyto.
        Emits live progress percentage and transfer metrics via progress_callback.
        Returns (success, error_or_success_message).
        """
        src_target = cls.get_source_target(settings, file_path)
        dst_target = cls.get_destination_target(settings, file_path)
        conf_to_use = config_path or RCLONE_CONF_PATH
        
        dest_type = settings.get("dest_type", "s3").lower()
        
        cmd = [
            cls.get_rclone_binary(), "copyto",
            "--config", str(conf_to_use),
            "--retries", "5",
            "--contimeout", "20s",
            "--timeout", "10m",
            "--ignore-existing",
            "--no-check-certificate",
            "--stats", "500ms",
            "--use-json-log",
            "-v",
        ]
        
        if dest_type == "s3":
            cmd.extend([
                "--s3-chunk-size", "5M",
                "--s3-upload-concurrency", "2",
                "--s3-force-path-style",
                "--s3-no-check-bucket"
            ])
        elif dest_type == "ftp":
            cmd.extend([
                "--ftp-no-check-certificate",
            ])

        cmd.extend([src_target, dst_target])
        
        proc = None
        try:
            proc = subprocess.Popen(
                cmd,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                text=True
            )
            
            # Register process with caller (for cancellation/stop support)
            if process_callback:
                process_callback(proc)
                
            err_lines = []
            last_pct = 0.0

            if proc.stderr:
                for raw_line in iter(proc.stderr.readline, ''):
                    if not raw_line:
                        break
                    line_str = raw_line.strip()
                    if not line_str:
                        continue
                    try:
                        msg_data = json.loads(line_str)
                        if "stats" in msg_data:
                            st = msg_data["stats"]
                            bytes_done = st.get("bytes", 0)
                            total_bytes = st.get("totalBytes", 0)
                            speed = st.get("speed", 0.0)
                            eta = st.get("eta", None)

                            pct = 0.0
                            transferring = st.get("transferring")
                            if transferring and isinstance(transferring, list) and len(transferring) > 0:
                                first = transferring[0]
                                pct = float(first.get("percentage", 0.0))
                                if not bytes_done:
                                    bytes_done = first.get("bytes", 0)
                                if not total_bytes:
                                    total_bytes = first.get("size", 0)
                                if not speed and "speed" in first:
                                    speed = first.get("speed", 0.0)
                                if eta is None and "eta" in first:
                                    eta = first.get("eta")
                            elif total_bytes > 0:
                                pct = round((bytes_done / total_bytes) * 100.0, 1)

                            last_pct = min(pct, 100.0)
                            if progress_callback:
                                progress_callback({
                                    "percentage": last_pct,
                                    "bytes": bytes_done,
                                    "total_bytes": total_bytes,
                                    "speed": speed,
                                    "eta": eta
                                })
                        elif msg_data.get("level") == "error":
                            err_lines.append(msg_data.get("msg", line_str))
                    except Exception:
                        err_lines.append(line_str)

            proc.wait(timeout=15)
            
            if proc.returncode == 0:
                if progress_callback:
                    progress_callback({
                        "percentage": 100.0,
                        "bytes": 0,
                        "total_bytes": 0,
                        "speed": 0.0,
                        "eta": 0
                    })
                return True, "Transferencia completada exitosamente."
            else:
                err_msg = "\n".join(err_lines[-3:]) or f"Código de error {proc.returncode}"
                return False, f"Fallo al transferir: {err_msg}"
        except subprocess.TimeoutExpired:
            if proc:
                proc.kill()
            return False, "Tiempo de espera de transferencia agotado (Timeout)."
        except Exception as e:
            return False, f"Excepción durante la transferencia: {str(e)}"

    @classmethod
    def ping_host(cls, host: str, port: int = 22, timeout: float = 3.0) -> Dict[str, Any]:
        """
        Tests DNS resolution, TCP port connectivity, and measures round-trip latency in ms.
        Works across all platforms without requiring root/sudo privileges.
        """
        import socket
        import time
        from urllib.parse import urlparse

        clean_host = (host or "").strip()
        if "://" in clean_host:
            parsed = urlparse(clean_host)
            clean_host = parsed.hostname or clean_host
            if parsed.port:
                port = parsed.port
            elif parsed.scheme == "https":
                port = 443
            elif parsed.scheme == "http":
                port = 80
        elif "/" in clean_host:
            clean_host = clean_host.split("/", 1)[0]
        if ":" in clean_host and not clean_host.startswith("["):
            parts = clean_host.split(":", 1)
            clean_host = parts[0]
            try:
                port = int(parts[1])
            except ValueError:
                pass

        res = {
            "host": clean_host,
            "port": port,
            "resolved_ip": None,
            "reachable": False,
            "latency_ms": None,
            "error": None,
            "details": ""
        }

        if not clean_host:
            res["error"] = "Host no especificado o vacío."
            return res

        # 1. DNS Resolution
        t0 = time.perf_counter()
        try:
            ip = socket.gethostbyname(clean_host)
            res["resolved_ip"] = ip
        except Exception as e:
            res["error"] = f"No se pudo resolver el host '{clean_host}': {e}"
            return res

        # 2. TCP Socket Connect (true round-trip latency)
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.settimeout(timeout)
        try:
            t_conn = time.perf_counter()
            sock.connect((ip, port))
            latency = (time.perf_counter() - t_conn) * 1000.0
            res["reachable"] = True
            res["latency_ms"] = round(latency, 1)
            res["details"] = f"Puerto {port} abierto. Latencia: {res['latency_ms']} ms"
        except socket.timeout:
            res["error"] = f"Tiempo de espera agotado ({timeout}s) en {clean_host}:{port}"
        except ConnectionRefusedError:
            # Server is reachable (sent RST reply), though specific port is closed
            latency = (time.perf_counter() - t0) * 1000.0
            res["reachable"] = True
            res["latency_ms"] = round(latency, 1)
            res["details"] = f"Servidor alcanzable ({res['latency_ms']} ms), pero puerto {port} cerrado."
        except Exception as e:
            res["error"] = f"Fallo al conectar a {clean_host}:{port} -> {e}"
        finally:
            sock.close()

        return res

    @classmethod
    def ping_endpoints(cls, settings: Dict[str, Any], target: Optional[str] = None) -> Dict[str, Any]:
        """
        Pings source (SFTP NAS), destination (S3 / FTP), or both based on target param.
        target can be 'source', 'destination', or 'all' (default).
        """
        from urllib.parse import urlparse

        clean_target = (target or "all").lower().strip()
        response: Dict[str, Any] = {
            "success": True,
            "target": clean_target
        }

        # 1. Source SFTP
        if clean_target in ("source", "all"):
            src_host = settings.get("source_host", "").strip()
            try:
                src_port = int(settings.get("source_port", 22) or 22)
            except ValueError:
                src_port = 22
            src_res = cls.ping_host(src_host, src_port)
            src_res["label"] = f"Origen: SFTP ({src_host}:{src_port})" if src_host else "Origen: SFTP"
            response["source"] = src_res

        # 2. Destination
        if clean_target in ("destination", "all"):
            dest_type = settings.get("dest_type", "s3").lower()
            if dest_type == "s3":
                endpoint = settings.get("s3_endpoint", "").strip()
                provider = settings.get("s3_provider", "AWS")
                if endpoint:
                    parsed = urlparse(endpoint if "://" in endpoint else f"https://{endpoint}")
                    dst_host = parsed.hostname or endpoint
                    dst_port = parsed.port or (443 if parsed.scheme == "https" else 80)
                else:
                    region = settings.get("s3_region", "us-east-1").strip() or "us-east-1"
                    dst_host = f"s3.{region}.amazonaws.com"
                    dst_port = 443
                dst_res = cls.ping_host(dst_host, dst_port)
                dst_res["label"] = f"Destino: S3 ({provider} - {dst_host}:{dst_port})"
            else:
                # FTP
                ftp_host = settings.get("ftp_host", "").strip()
                try:
                    ftp_port = int(settings.get("ftp_port", 21) or 21)
                except ValueError:
                    ftp_port = 21
                dst_res = cls.ping_host(ftp_host, ftp_port)
                dst_res["label"] = f"Destino: FTP ({ftp_host}:{ftp_port})" if ftp_host else "Destino: FTP"
            response["destination"] = dst_res

        return response
